export type EmptyIcon = keyof typeof ICONS;

/**
 * État vide : icône, titre, explication et action. `compact` pour l'intérieur d'une carte.
 */
export function EmptyState({
  icon = "document",
  title,
  children,
  action,
  compact = false,
}: {
  icon?: EmptyIcon;
  title: string;
  children?: ReactNode;
  action?: { href: string; label: string };
  compact?: boolean;
}) {
  return (
    <div className={`empty-state${compact ? " is-compact" : ""}`}>
      <span className="empty-state-icon" aria-hidden>
        <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={1.7} strokeLinecap="round" strokeLinejoin="round" width={compact ? 20 : 26} height={compact ? 20 : 26}>
          {ICONS[icon].split(/(?=M)/).map((d, i) => (
            <path key={i} d={d} />
          ))}
        </svg>
      </span>
      <p className="empty-state-title">{title}</p>
      {children && <p className="empty-state-text">{children}</p>}
      {action && (
        <Link href={action.href} className="admin-btn admin-btn-primary">
          {action.label}
        </Link>
      )}
    </div>
  );
}
